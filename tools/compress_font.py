    comp_size = len(compressed)

    # Print statistics to stderr
    print(f"// Original size:    {orig_size} bytes", file=sys.stderr)
    print(f"// Compressed size:  {comp_size} bytes", file=sys.stderr)
    print(f"// Flash saved:      {orig_size - comp_size} bytes ({(1.0 - comp_size / orig_size) * 100:.1f}%)", file=sys.stderr)

    # Print C-formatted array to stdout
    print("// RLE-compressed 7x10 font data")
    for idx, b in enumerate(compressed):
        print(f"0x{b:02X}, ", end="")
        if (idx + 1) % 12 == 0:
            print()
    print()
