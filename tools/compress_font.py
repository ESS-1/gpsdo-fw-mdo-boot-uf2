def compress_font(data):
    packed = []
    i = 0
    total = len(data)

    while i < total:
        # Extract raw bits [14:10] (mask 0x7C00)
        raw_val = data[i] & 0x7C00
        pixel_pattern = raw_val >> 7

        # Count consecutive identical rows (max 8 repetitions per byte)
        run_len = 0
        while i < total and (data[i] & 0x7C00) == raw_val and run_len < 8:
            run_len += 1
            i += 1

        # Pack pixel pattern [7:3] with repetition count code [2:0] (0..7 for 1..8 repeats)
        packed_byte = pixel_pattern | (run_len - 1)
        packed.append(packed_byte)

    return packed

