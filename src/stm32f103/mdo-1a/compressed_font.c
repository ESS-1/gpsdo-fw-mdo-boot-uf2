void compressed_font_init(void)
{
    const uint8_t* src = Font7x10_rle;
    uint16_t* dst = Font7x10_decompressed;
    uint16_t* dst_end = Font7x10_decompressed + FONT_DATA_SIZE;

    while (dst < dst_end) {
        uint8_t b = *src++;

        // Extract 5 pixel bits from [7:3] and restore them to positions [14:10] in uint16_t
        uint16_t pattern = ((uint16_t)(b & 0xF8)) << 7;

        // Extract 3-bit repeat count [2:0] -> range 1..8
        uint32_t count = (b & 0x07) + 1;

        // Write to RAM buffer
        while (count-- && dst < dst_end) {
            *dst++ = pattern;
        }
    }
}
